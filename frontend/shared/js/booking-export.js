const BOOKING_EXPORT_COLUMNS = [
  ['booking_id', 'Booking ID'],
  ['booking_status', 'Status'],
  ['booking_date', 'Scheduled date'],
  ['booking_time', 'Time'],
  ['destination', 'Destination / service'],
  ['target_type', 'Target type'],
  ['traveler_name', 'Traveler'],
  ['contact', 'Contact'],
  ['adults', 'Adults'],
  ['children', 'Children'],
  ['pwd', 'PWD'],
  ['assigned_guide', 'Assigned guide'],
  ['check_in', 'Check-in'],
  ['check_out', 'Check-out'],
  ['service_fee', 'Service fee'],
  ['notes', 'Notes'],
  ['created_at', 'Created at'],
  ['approved_at', 'Approved at'],
  ['completed_at', 'Completed at']
];

function previousManilaMonth(referenceDate = new Date()) {
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-US', {
    timeZone: 'Asia/Manila',
    year: 'numeric',
    month: 'numeric'
  }).formatToParts(referenceDate).map((part) => [part.type, part.value]));
  let year = Number(parts.year);
  let month = Number(parts.month) - 1;
  if (!month) {
    month = 12;
    year -= 1;
  }
  return `${year}-${String(month).padStart(2, '0')}`;
}

function escapeBookingExportHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function bookingExportCsvCell(value) {
  let text = String(value ?? '');
  if (/^[\s]*[=+\-@]/.test(text)) text = `'${text}`;
  return `"${text.replace(/"/g, '""')}"`;
}

function bookingHistoryCsv(rows) {
  const records = Array.isArray(rows) ? rows : [];
  const header = BOOKING_EXPORT_COLUMNS.map(([, label]) => bookingExportCsvCell(label)).join(',');
  const body = records.map((row) =>
    BOOKING_EXPORT_COLUMNS.map(([key]) => bookingExportCsvCell(row[key])).join(',')
  );
  return `\uFEFF${[header, ...body].join('\r\n')}`;
}

function bookingHistoryMonthLabel(month) {
  const date = new Date(`${month}-01T00:00:00Z`);
  if (Number.isNaN(date.getTime())) return month;
  return new Intl.DateTimeFormat('en-PH', {
    timeZone: 'UTC',
    year: 'numeric',
    month: 'long'
  }).format(date);
}

function bookingHistoryPrintHtml(rows, month) {
  const records = Array.isArray(rows) ? rows : [];
  const title = `Booking history — ${bookingHistoryMonthLabel(month)}`;
  const headers = BOOKING_EXPORT_COLUMNS.map(([, label]) =>
    `<th scope="col">${escapeBookingExportHtml(label)}</th>`
  ).join('');
  const body = records.map((row) => `<tr>${BOOKING_EXPORT_COLUMNS.map(([key]) =>
    `<td>${escapeBookingExportHtml(row[key])}</td>`
  ).join('')}</tr>`).join('');
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <title>${escapeBookingExportHtml(title)}</title>
    <style>
      body { font: 12px/1.45 Arial, sans-serif; color: #172033; margin: 24px; }
      h1 { font-size: 20px; margin: 0 0 4px; }
      p { margin: 0 0 18px; color: #566070; }
      table { width: 100%; border-collapse: collapse; table-layout: fixed; }
      th, td { border: 1px solid #cbd3dc; padding: 5px; text-align: left; vertical-align: top; overflow-wrap: anywhere; }
      th { background: #edf2f7; }
      @page { size: landscape; margin: 10mm; }
    </style>
  </head>
  <body>
    <h1>${escapeBookingExportHtml(title)}</h1>
    <p>${records.length} booking${records.length === 1 ? '' : 's'} • Generated by Montalban Navigator</p>
    <table>
      <thead><tr>${headers}</tr></thead>
      <tbody>${body}</tbody>
    </table>
  </body>
</html>`;
}

async function loadBookingHistoryForMonth(month, client = supabaseClient) {
  if (!month || !/^\d{4}-(0[1-9]|1[0-2])$/.test(month)) {
    throw new Error('Choose a valid booking month.');
  }
  if (!client) throw new Error('Connect this portal to Supabase before exporting.');
  const { data, error } = await client.rpc('export_bookings_for_month', {
    p_month: `${month}-01`
  });
  if (error) throw error;
  return Array.isArray(data) ? data : [];
}

async function downloadBookingHistoryCsv(month, browserWindow = window) {
  const rows = await loadBookingHistoryForMonth(month);
  if (!rows.length) throw new Error('There are no bookings in the selected month.');
  const blob = new Blob([bookingHistoryCsv(rows)], { type: 'text/csv;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = browserWindow.document.createElement('a');
  link.href = url;
  link.download = `booking-history-${month}.csv`;
  link.hidden = true;
  browserWindow.document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}

async function printBookingHistory(month, browserWindow = window) {
  const popup = browserWindow.open('', '_blank');
  if (!popup) throw new Error('Allow pop-ups for this site, then try printing again.');
  try {
    popup.opener = null;
    const rows = await loadBookingHistoryForMonth(month);
    if (!rows.length) {
      popup.close();
      throw new Error('There are no bookings in the selected month.');
    }
    popup.document.open();
    popup.document.write(bookingHistoryPrintHtml(rows, month));
    popup.document.close();
    popup.focus();
    popup.print();
  } catch (error) {
    popup.close();
    throw error;
  }
}

function setupBookingHistoryExport({ containerId }) {
  const container = document.getElementById(containerId);
  if (!container || container.dataset.exportReady === 'true') return;
  container.dataset.exportReady = 'true';
  const month = container.querySelector('[data-export-month]');
  const csvButton = container.querySelector('[data-export-csv]');
  const printButton = container.querySelector('[data-export-print]');
  const message = container.querySelector('[data-export-message]');
  if (!month || !csvButton || !printButton || !message) {
    throw new Error(`Booking export controls are incomplete in #${containerId}.`);
  }
  month.value = previousManilaMonth();

  const run = async (action) => {
    csvButton.disabled = true;
    printButton.disabled = true;
    message.hidden = true;
    try {
      await action(month.value);
    } catch (error) {
      message.textContent = error?.message || String(error);
      message.classList.toggle('error-message', true);
      message.hidden = false;
    } finally {
      csvButton.disabled = false;
      printButton.disabled = false;
    }
  };

  csvButton.addEventListener('click', () => run(downloadBookingHistoryCsv));
  printButton.addEventListener('click', () => run(printBookingHistory));
}

window.BookingHistoryExport = {
  setup: setupBookingHistoryExport,
  exportPrint: printBookingHistory
};
